/**
 * Returns only images that are verified AND publicationApproved.
 * These are the only images safe to display publicly.
 */
export function getPublishedPhotos(): PhotoMapping[] {
  return PHOTO_MAPPING_MANIFEST.filter(
    (p) => p.verificationStatus === "verified" && p.publicationApproved === true
  );
}

/**
 * Returns photos by category/role.
 */
export function getPhotosByRole(role: PhotoRole): PhotoMapping[] {
  return PHOTO_MAPPING_MANIFEST.filter(
    (p) => p.role === role && p.verificationStatus === "verified" && p.publicationApproved === true
  );
}

/**
 * Returns photos that need review (unverified).
 */
export function getPendingReviewPhotos(): PhotoMapping[] {
  return PHOTO_MAPPING_MANIFEST.filter(
    (p) => p.verificationStatus === "needs_review"
  );
}

/**
 * Returns photos grouped by verified person (displayName).
 * Only includes verified + approved photos with a displayName.
 */
export function getPhotosByPerson(): Record<string, PhotoMapping[]> {
  const published = getPublishedPhotos();
  const grouped: Record<string, PhotoMapping[]> = {};
  for (const p of published) {
    if (p.displayName) {
      if (!grouped[p.displayName]) grouped[p.displayName] = [];
      grouped[p.displayName].push(p);
    }
  }
  return grouped;
}
